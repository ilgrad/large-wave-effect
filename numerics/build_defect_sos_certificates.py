"""Generate the exact SOS defect certificates checked by exact/pari/defect_sos.gp.

For odd N the node-0 response is F(psi) = sum_r b_r sin<C_r, psi> on the orbit-closure torus psi in T^M
(M = phi(2N)/2, C the integer subtorus coordinates of verify_defect_moment_sos.py), and A_N = max F.
With z_s = e^{i psi_s} and a monomial basis v = (z^{B_a})_a, a Hermitian Q >= 0 with

    c - F = v* Q v + r        (c = tr Q, r a Laurent polynomial with tiny coefficients)

gives A_N <= c + ||r||_1.  This script solves the SOS side of the trigonometric Lasserre relaxation
(Clarabel), projects Q onto the coefficient constraints, shifts it by eta*I to make it strictly positive
definite, and rounds it to Gaussian integers over a common denominator.  It proves nothing: the PARI script
recomputes the weights from Sturm enclosures, the subtorus relations, the exact fraction-free LDL* of Q,
the residual r and the certified bound, all in exact arithmetic.

    uv run --script numerics/build_defect_sos_certificates.py   # writes exact/pari/defect_sos_certs.gp
"""

from __future__ import annotations

from fractions import Fraction
from pathlib import Path

import cvxpy as cp
import numpy as np
from verify_defect_moment_sos import build_basis, integer_coord_matrix, weights

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "exact" / "pari" / "defect_sos_certs.gp"
CASES = [(9, "obj"), (15, "obj+"), (21, "obj+:3")]
DEN = 10**12
ETA = 1e-9


def solve(n: int, spec: str) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    u, b, _ = weights(n)
    c = integer_coord_matrix(n)
    basis = build_basis(spec, c)
    nb, big_m = len(basis), c.shape[1]
    zero = (0,) * big_m
    groups: dict[tuple[int, ...], list[tuple[int, int]]] = {}
    for a in range(nb):
        for k in range(nb):
            groups.setdefault(tuple((basis[k] - basis[a]).tolist()), []).append((a, k))
    target: dict[tuple[int, ...], complex] = {}
    for r in range(c.shape[0]):
        p, q = tuple(c[r].tolist()), tuple((-c[r]).tolist())
        target[p] = target.get(p, 0) + 0.5j * b[r]
        target[q] = target.get(q, 0) - 0.5j * b[r]
    assert all(k in groups for k in target), "basis does not cover the objective"

    qv = cp.Variable((nb, nb), hermitian=True)
    cons = [qv >> 0]
    for d, pairs in groups.items():
        if d != zero and d > tuple(-x for x in d):  # one of each conjugate pair
            cons.append(sum(qv[a, k] for a, k in pairs) == target.get(d, 0))
    cp.Problem(cp.Minimize(cp.real(cp.trace(qv))), cons).solve(solver="CLARABEL")
    q = np.array(qv.value, dtype=complex)
    q = (q + q.conj().T) / 2

    # Orthogonal projection onto the coefficient constraints: the groups partition the off-diagonal pairs.
    for d, pairs in groups.items():
        if d == zero:
            continue
        gap = target.get(d, 0) - sum(q[a, k] for a, k in pairs)
        for a, k in pairs:
            q[a, k] += gap / len(pairs)
    shift = max(0.0, -float(np.linalg.eigvalsh(q).min())) + ETA
    q += shift * np.eye(nb)
    return c, basis, q, u


def gp_matrix(m: np.ndarray) -> str:
    return "[" + ";".join(",".join(str(int(x)) for x in row) for row in m) + "]"


def gauss_int(z: complex) -> str:
    re, im = round(z.real * DEN), round(z.imag * DEN)
    return f"{re}" if im == 0 else f"{re}{im:+d}*I"


def wrap(items: list[str], per_line: int = 6) -> str:
    lines = [", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    return ",\n    ".join(lines)


def main() -> int:
    blocks = []
    for n, spec in CASES:
        c, basis, q, u = solve(n, spec)
        tri = [gauss_int(q[i, j]) for i in range(len(basis)) for j in range(i + 1)]
        # The claim is rounded down from the float estimate; the PARI script decides whether it is proved.
        est = u - float(np.trace(q).real)
        claim = Fraction(int((est - 1e-9) * 10**8), 10**8)
        print(
            f"N={n:>3} basis={spec:<7} |B|={len(basis):>3}  defect estimate {est:.9f}  claim {float(claim)}"
        )
        blocks.append(
            f"  [{n}, {gp_matrix(c)}, {gp_matrix(basis)}, {DEN},\n   [{wrap(tri)}],\n"
            f"   {claim.numerator}/{claim.denominator}]"
        )
    OUT.write_text(
        "\\\\ Generated by numerics/build_defect_sos_certificates.py; checked by exact/pari/defect_sos.gp.\n"
        "\\\\ Each entry: [N, C, B, den, Q, claim].  C: subtorus coordinates (phi_r = <C_r, psi>); B: monomial\n"
        "\\\\ basis exponents; Q: Gram matrix, lower triangle row by row, Gaussian integers over den;\n"
        "\\\\ claim: the defect lower bound to be proved.\n"
        "{\ndefect_certs = [\n" + ",\n".join(blocks) + "\n];\n}\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
